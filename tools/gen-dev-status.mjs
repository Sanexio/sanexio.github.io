#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_FEED =
  '/Users/clusteradm/Cortex/projects/Juvantis/juvantis-mvp/web/assets/features-feed.json';
const OUTPUT = 'src/data/dev-status.ts';
const BLOCKED_WORDS = ['FLAME', 'qwen', 'ollama', 'github.com'];

function parseArgs(argv) {
  const args = { feed: DEFAULT_FEED };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--feed') {
      if (!argv[i + 1]) throw new Error('Missing value for --feed');
      args.feed = argv[i + 1];
      i += 1;
    } else if (arg.startsWith('--feed=')) {
      args.feed = arg.slice('--feed='.length);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }

  return args;
}

function versionNumber(value) {
  if (typeof value !== 'string') return 0;
  const match = value.match(/^V(\d+)$/i);
  return match ? Number.parseInt(match[1], 10) : 0;
}

function highestVersion(features, key) {
  const highest = features.reduce(
    (max, feature) => Math.max(max, versionNumber(feature[key])),
    0,
  );

  return highest > 0 ? `V${String(highest).padStart(3, '0')}` : null;
}

function assertString(value, label) {
  if (typeof value !== 'string' || value.trim() === '') {
    throw new Error(`Invalid or missing ${label}`);
  }

  return value.trim();
}

function normalizeFeature(feature) {
  return {
    name: assertString(feature.name, 'feature.name'),
    beschreibung: assertString(feature.beschreibung, 'feature.beschreibung'),
    seitIos: typeof feature.seit_ios === 'string' ? feature.seit_ios : null,
    seitWeb: typeof feature.seit_web === 'string' ? feature.seit_web : null,
  };
}

function serialize(value) {
  return JSON.stringify(value, null, 2)
    .replaceAll('"standDatum"', 'standDatum')
    .replaceAll('"appVersion"', 'appVersion')
    .replaceAll('"webVersion"', 'webVersion')
    .replaceAll('"weitereFeatures"', 'weitereFeatures')
    .replaceAll('"features"', 'features')
    .replaceAll('"name"', 'name')
    .replaceAll('"beschreibung"', 'beschreibung')
    .replaceAll('"seitIos"', 'seitIos')
    .replaceAll('"seitWeb"', 'seitWeb');
}

function renderTs(data) {
  return `// AUTO-GENERATED — DO NOT EDIT
// Generated by tools/gen-dev-status.mjs from the pitch-filtered Juvantis feature feed.

export interface DevStatusFeature {
  name: string;
  beschreibung: string;
  seitIos: string | null;
  seitWeb: string | null;
}

export interface DevStatus {
  standDatum: string;
  appVersion: string | null;
  webVersion: string | null;
  weitereFeatures: number;
  features: DevStatusFeature[];
}

export const devStatus: DevStatus = ${serialize(data)};
`;
}

function guardOutput(output) {
  const lowered = output.toLowerCase();
  const blocked = BLOCKED_WORDS.find((word) => lowered.includes(word.toLowerCase()));

  if (blocked) {
    throw new Error(`Blocked internal term found in generated output: ${blocked}`);
  }
}

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { feed } = parseArgs(process.argv.slice(2));
const feedPath = resolve(feed);
const outputPath = resolve(rootDir, OUTPUT);
const raw = await readFile(feedPath, 'utf8');
const parsed = JSON.parse(raw);

if (!Array.isArray(parsed.features)) {
  throw new Error('Invalid feed: features must be an array');
}

const generatedAt = assertString(parsed.generated_at, 'generated_at');
const standDatum = generatedAt.slice(0, 10);

if (!/^\d{4}-\d{2}-\d{2}$/.test(standDatum)) {
  throw new Error(`Invalid generated_at date: ${generatedAt}`);
}

const normalized = parsed.features
  .map(normalizeFeature)
  .sort((a, b) => {
    const iosDiff = versionNumber(b.seitIos) - versionNumber(a.seitIos);
    if (iosDiff !== 0) return iosDiff;
    return versionNumber(b.seitWeb) - versionNumber(a.seitWeb);
  });

const data = {
  standDatum,
  appVersion: highestVersion(parsed.features, 'seit_ios'),
  webVersion: highestVersion(parsed.features, 'seit_web'),
  weitereFeatures: Math.max(0, normalized.length - 10),
  features: normalized.slice(0, 10),
};

const output = renderTs(data);
guardOutput(output);

await writeFile(outputPath, output, 'utf8');
console.log(`Wrote ${OUTPUT} from ${feedPath}`);
