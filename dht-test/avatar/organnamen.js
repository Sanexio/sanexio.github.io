export function germanOrganName(entry) {
  const concept = terms[entry.ta2_id?.replace(/^TA2:/, '')];
  if (!concept || entry.quality !== 'gesichert') return '';
  const side = /_L$/.test(entry.mesh) ? ' links' : /_R$/.test(entry.mesh) ? ' rechts' : '';
  return /\b(link|recht)/i.test(concept) ? concept : concept + side;
}
export function organSearchTerms(entry) {
  if (entry.quality !== 'gesichert') return '';
  const name = entry.mesh;
  if (/^Allen_/.test(name)) return 'Gehirn';
  if (/^VH_F_(?:left|right)_bronchopulmonary|bronchopulmonary_segment|hilum_of_lung/i.test(name)) return 'Lunge';
  if (/^VH_F_(?:left|right)_cardiac_atrium$|^VH_F_(?:left|right)_ventricle$|^VH_F_interventricular_septum$/.test(name)) return 'Herz';
  if (/^VH_F_(?:duodenum|jejenum|ileum)/.test(name)) return 'Dünndarm';
  if (/^VH_F_(?:ascending_colon|transverse_colon|descending_colon|sigmoid_colon|caecum)/.test(name)) return 'Dickdarm';
  return '';
}
